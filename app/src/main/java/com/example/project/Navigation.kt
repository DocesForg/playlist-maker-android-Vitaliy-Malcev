package com.example.project

/**
 * Запечатанный (sealed) класс для типобезопасного описания экранов приложения.
 * Широко используется в Jetpack Compose Navigation: позволяет компилятору
 * проверять полноту `when`-выражений и исключает возможность передачи
 * недопустимых или строковых маршрутов.
 *
 * @property route Уникальный идентификатор маршрута, используемый навигатором.
 */
sealed class Screen(val route: String) {
    
    /**
     * Главный экран приложения (стартовая страница, лента, дашборд и т.п.).
     * Обычно является стартовой точкой навигации.
     */
    object Main : Screen("main")
    
    /**
     * Экран поиска. Предназначен для фильтрации или нахождения контента/пользователей.
     */
    object Search : Screen("search")
    
    /**
     * Экран настроек. Содержит параметры конфигурации приложения или профиля пользователя.
     */
    object Settings : Screen("settings")
}